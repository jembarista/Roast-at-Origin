const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const nodes = new Map(['journeyChoice','resultView','valuePanel','carbonPanel','volumePanel','viewResultsLink'].map(id=>[id,{value:'money',hidden:false,addEventListener(type,fn){this[type]=fn}}]));
const source = fs.readFileSync(path.join(__dirname,'../view-switch.js'),'utf8');
vm.runInNewContext(source,{document:{getElementById:id=>nodes.get(id)}});
assert.equal(nodes.get('valuePanel').hidden,false);
assert.equal(nodes.get('carbonPanel').hidden,true);
assert.equal(nodes.get('volumePanel').hidden,true);
nodes.get('resultView').value='carbon';nodes.get('resultView').change();
assert.equal(nodes.get('valuePanel').hidden,true);
assert.equal(nodes.get('carbonPanel').hidden,false);
assert.equal(nodes.get('volumePanel').hidden,false);
assert.equal(nodes.get('viewResultsLink').href,'#carbonPanel');
nodes.get('resultView').value='money';nodes.get('resultView').change();
assert.equal(nodes.get('valuePanel').hidden,false);
assert.equal(nodes.get('carbonPanel').hidden,true);
assert.equal(nodes.get('viewResultsLink').href,'#valuePanel');
nodes.get('journeyChoice').value='';nodes.get('resultView').change();
assert.equal(nodes.get('valuePanel').hidden,true);assert.equal(nodes.get('carbonPanel').hidden,true);
console.log('PASS result-view switching, journey gate and result links');
